/**
 * Produce a deterministic dataset of related movement sequences by sampling
 * step variants from workflow templates. Same seed -> same dataset. The variant
 * sampling yields new-but-related sequences, so a model trained on one split
 * can be measured for generalization on another.
 */
export function generateSyntheticMovementDataset(options: SyntheticMovementOptions): MovementTrainingDataset {
  const workflows = options.workflows ?? DEFAULT_SYNTHETIC_WORKFLOWS;
  const random = makePrng(options.seed);
  const sequences: MovementSequence[] = [];

  for (let index = 0; index < options.sequenceCount; index += 1) {
    const workflow = workflows[Math.floor(random() * workflows.length) % workflows.length];
    if (!workflow) {
      continue;
    }
    const tokens = workflow.steps.map((variants) => {
      const choice = variants[Math.floor(random() * variants.length) % variants.length];
      return choice ?? variants[0] ?? "device:noop";
    });
    sequences.push({ id: `${workflow.name}-${index}`, tokens });
  }

  return { version: 1, sequences };
}

/** Deterministically split a dataset into train/test by stride (no RNG needed). */
export function splitMovementDataset(
  dataset: MovementTrainingDataset,
  holdoutEvery = 4,
): { train: MovementTrainingDataset; test: MovementTrainingDataset } {
  const stride = Math.max(2, Math.trunc(holdoutEvery));
  const train: MovementSequence[] = [];
  const test: MovementSequence[] = [];
  dataset.sequences.forEach((sequence, index) => {
    if (index % stride === stride - 1) {
      test.push(sequence);
    } else {
      train.push(sequence);
    }
  });
  return {
    train: { version: 1, sequences: train },
    test: { version: 1, sequences: test },
  };
}
